"""Service registry + generators. Single source of truth: `[tool.rio.service]` in each apps/<name>/pyproject.toml.

python tooling/service.py list                       service names
python tooling/service.py get <svc> <field>          module | port | database | database_env | depends_on ...
python tooling/service.py generate [--check]         (re)write compose*.yaml, docker-bake.services.hcl and the
                                                     package-manifest region of the Dockerfile (CI: --check)
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN, END = "# >>> generated: package manifests (tooling/service.py)", "# <<< generated"


@dataclass
class Service:
    name: str
    module: str
    port: int
    database: str
    database_env: str
    kind: str = "domain"
    depends_on: list[str] = field(default_factory=list)
    env: dict[str, str] = field(default_factory=dict)


def services() -> list[Service]:
    out = []
    for pp in sorted((ROOT / "apps").glob("*/pyproject.toml")):
        data = tomllib.loads(pp.read_text())
        cfg = data.get("tool", {}).get("rio", {}).get("service")
        if cfg is None:
            continue
        out.append(
            Service(
                name=pp.parent.name,
                module=cfg["module"],
                port=int(cfg["port"]),
                database=cfg.get("database", pp.parent.name),
                database_env=cfg["database_env"],
                kind=cfg.get("kind", "domain"),
                depends_on=list(cfg.get("depends_on", [])),
                env=dict(cfg.get("env", {})),
            )
        )
    ports = [s.port for s in out]
    if len(ports) != len(set(ports)):
        raise SystemExit("duplicate service ports: " + ", ".join(f"{s.name}={s.port}" for s in out))
    return out


def packages() -> list[str]:
    return sorted(p.parent.name for p in (ROOT / "packages").glob("*/pyproject.toml"))


# ------------------------------------------------------------------------------------------------ generators
HEADER = "# GENERATED by tooling/service.py from apps/*/pyproject.toml [tool.rio.service] - do not edit.\n"


def _env_block(s: Service, indent: str) -> str:
    env = {
        s.database_env: f"postgresql+asyncpg://rio:${{POSTGRES_PASSWORD:?set POSTGRES_PASSWORD}}@db:5432/{s.database}",
        "RIO_SECRET_KEY": "${RIO_SECRET_KEY:-}",
        "RIO_SERVICE_KEY": "${RIO_SERVICE_KEY:-}",
        **s.env,
    }
    return "\n".join(f'{indent}{k}: "{v}"' for k, v in env.items())


def compose_base(svcs: list[Service]) -> str:
    dbs = ",".join(s.database for s in svcs)
    parts = [
        HEADER,
        "name: rio\nservices:\n",
        f"""  db:
    image: postgres:17-alpine
    environment:
      POSTGRES_USER: rio
      POSTGRES_DB: postgres
      POSTGRES_PASSWORD: ${{POSTGRES_PASSWORD:?set POSTGRES_PASSWORD}}
      RIO_DATABASES: "{dbs}"          # one database per service, created on first start
    volumes:
      - pgdata:/var/lib/postgresql/data
      - ./docker/postgres/init-databases.sh:/docker-entrypoint-initdb.d/10-init-databases.sh:ro
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U rio -d postgres"]
      interval: 5s
      timeout: 3s
      retries: 10
    restart: unless-stopped
    init: true
""",
    ]
    for s in svcs:
        build = f"""    build:
      context: .
      target: ${{RIO_TARGET:-runtime}}
      args:
        SERVICE: {s.name}
        SERVICE_MODULE: {s.module}
        SERVICE_PORT: "{s.port}"
"""
        dep_lines = "".join(
            f"      {d}:\n        condition: service_healthy\n" for d in s.depends_on
        )
        parts.append(
            f"""
  {s.name}-migrate:
{build}    image: rio-{s.name}:${{RIO_TAG:-local}}
    command: ["alembic", "upgrade", "head"]
    environment:
{_env_block(s, "      ")}
    depends_on:
      db:
        condition: service_healthy
    restart: "no"

  {s.name}:
{build}    image: rio-{s.name}:${{RIO_TAG:-local}}
    environment:
{_env_block(s, "      ")}
    ports: ["${{{s.name.upper()}_PORT:-{s.port}}}:{s.port}"]
    init: true            # tini as PID 1: reaps zombies, forwards SIGTERM
    stop_grace_period: 25s  # > uvicorn --timeout-graceful-shutdown (20s)
    depends_on:
      db:
        condition: service_healthy
      {s.name}-migrate:
        condition: service_completed_successfully
{dep_lines}    healthcheck:
      test: ["CMD", "python", "-c", "import urllib.request as u,sys; sys.exit(u.urlopen('http://127.0.0.1:{s.port}/health/ready', timeout=2).status != 200)"]
      interval: 10s
      timeout: 3s
      retries: 6
      start_period: 10s
    restart: unless-stopped
"""
        )
    parts.append("\nvolumes:\n  pgdata:\n")
    return "".join(parts)


def compose_overlay(env: str, svcs: list[Service]) -> str:
    out = [HEADER]
    if env == "dev":
        out.append(
            "# Dev: hot reload from bind-mounted source; tables are created automatically.\nservices:\n"
        )
        for s in svcs:
            out.append(
                f"""  {s.name}:
    environment:
      RIO_ENVIRONMENT: development
      RIO_AUTO_CREATE_TABLES: "true"
      RIO_SECRET_KEY: dev-secret-not-for-production
      RIO_SERVICE_KEY: dev-service-key
      RIO_DEBUG: "true"
    volumes:
      - ./apps/{s.name}/src:/workspace/apps/{s.name}/src
      - ./packages:/workspace/packages
    working_dir: /workspace
  {s.name}-migrate:
    working_dir: /workspace
    command: ["alembic", "-c", "apps/{s.name}/alembic.ini", "upgrade", "head"]
"""
            )
    elif env == "staging":
        out.append(
            "# Staging: same slim image shape as prod, docs + playground on, locked-down container.\nservices:\n"
        )
        for s in svcs:
            out.append(
                f"""  {s.name}:
    environment:
      RIO_SECRET_KEY: ${{RIO_SECRET_KEY:?set RIO_SECRET_KEY}}
      RIO_SERVICE_KEY: ${{RIO_SERVICE_KEY:?set RIO_SERVICE_KEY}}
    read_only: true
    tmpfs: [/tmp]
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    deploy:
      resources:
        limits: {{ cpus: "1.0", memory: 256M }}
"""
            )
    else:
        out.append("# Prod: docs/playground off, replicas, stricter limits.\nservices:\n")
        for s in svcs:
            out.append(
                f"""  {s.name}:
    environment:
      RIO_SECRET_KEY: ${{RIO_SECRET_KEY:?set RIO_SECRET_KEY}}
      RIO_SERVICE_KEY: ${{RIO_SERVICE_KEY:?set RIO_SERVICE_KEY}}
      RIO_PLAYGROUND_ENABLED: "false"
      RIO_ALLOWED_HOSTS: ${{RIO_ALLOWED_HOSTS:-["*"]}}
    read_only: true
    tmpfs: [/tmp]
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    deploy:
      replicas: 2
      resources:
        limits: {{ cpus: "1.0", memory: 384M }}
"""
            )
    return "".join(out)


def bake_services(svcs: list[Service]) -> str:
    def entry(s: Service) -> str:
        return f'    {s.name} = {{ module = "{s.module}", port = "{s.port}" }}'

    return (
        "// GENERATED by tooling/service.py - do not edit.\n"
        'variable "SERVICES" {\n  default = {\n' + "\n".join(entry(s) for s in svcs) + "\n  }\n}\n"
    )


def dockerfile_region() -> str:
    lines = [BEGIN]
    for p in packages():
        lines.append(
            f"    --mount=type=bind,source=packages/{p}/pyproject.toml,target=packages/{p}/pyproject.toml \\"
        )
    lines.append(END)
    return "\n".join(lines)


def patched_dockerfile() -> str:
    text = (ROOT / "Dockerfile").read_text()
    a, b = text.index(BEGIN), text.index(END) + len(END)
    return text[:a] + dockerfile_region() + text[b:]


def outputs() -> dict[str, str]:
    svcs = services()
    files = {
        "compose.yaml": compose_base(svcs),
        "compose.dev.yaml": compose_overlay("dev", svcs),
        "compose.staging.yaml": compose_overlay("staging", svcs),
        "compose.prod.yaml": compose_overlay("prod", svcs),
        "docker-bake.services.hcl": bake_services(svcs),
    }
    if (ROOT / "Dockerfile").exists() and BEGIN in (ROOT / "Dockerfile").read_text():
        files["Dockerfile"] = patched_dockerfile()
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    g = sub.add_parser("get")
    g.add_argument("service")
    g.add_argument("field")
    gen = sub.add_parser("generate")
    gen.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if args.cmd == "list":
        print("\n".join(s.name for s in services()))
    elif args.cmd == "get":
        svc = next((s for s in services() if s.name == args.service), None)
        if svc is None:
            print(
                f"unknown service '{args.service}'; known: {[s.name for s in services()]}",
                file=sys.stderr,
            )
            return 2
        val = getattr(svc, args.field)
        print(json.dumps(val) if isinstance(val, dict | list) else val)
    else:
        stale = []
        for name, content in outputs().items():
            path = ROOT / name
            if args.check:
                if not path.exists() or path.read_text() != content:
                    stale.append(name)
            else:
                path.write_text(content)
                print(f"wrote {name}")
        if stale:
            print(
                "stale generated files: " + ", ".join(stale) + "  -> run scripts/generate.sh",
                file=sys.stderr,
            )
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
