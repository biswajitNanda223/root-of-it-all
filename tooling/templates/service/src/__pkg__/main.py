from __future__ import annotations

from fastapi import FastAPI

from __pkg__.api.v1 import notes
from __pkg__.config import ServiceSettings, get_settings
from __pkg__.infrastructure.models import Base
from rio_web import create_service_app, database_lifespan

DESCRIPTION = "**__title__ service.** Generated by `scripts/new-service.sh`; edit freely."


def create_app(settings: ServiceSettings | None = None) -> FastAPI:
    return create_service_app(
        settings or get_settings(),
        title="__title__ service",
        description=DESCRIPTION,
        tags=[{"name": "notes", "description": "Example resource - replace with your domain."}],
        lifespan=database_lifespan(metadata=Base.metadata),
        routers=[notes.router],
    )


def app_factory() -> FastAPI:
    return create_app()
