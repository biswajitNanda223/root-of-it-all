"""Ports: the service layer only knows these interfaces."""

from __future__ import annotations

from decimal import Decimal
from typing import Protocol

from catalog_service.domain.entities import Category, Product, Reservation, StockLine


class CategoryRepository(Protocol):
    async def add(self, *, name: str, slug: str) -> Category: ...
    async def list(self) -> list[Category]: ...
    async def get_by_slug(self, slug: str) -> Category | None: ...
    async def get(self, category_id: int) -> Category | None: ...


class ProductFilter(Protocol):
    """Read-only view (properties are covariant, so a pydantic model with narrower types satisfies it)."""

    @property
    def q(self) -> str | None: ...
    @property
    def category_id(self) -> int | None: ...
    @property
    def min_price(self) -> Decimal | None: ...
    @property
    def max_price(self) -> Decimal | None: ...
    @property
    def in_stock(self) -> bool | None: ...
    @property
    def sort(self) -> str: ...
    @property
    def limit(self) -> int: ...
    @property
    def offset(self) -> int: ...


class ProductRepository(Protocol):
    async def add(self, **fields: object) -> Product: ...
    async def get(self, product_id: int) -> Product | None: ...
    async def get_by_sku(self, sku: str) -> Product | None: ...
    async def search(self, f: ProductFilter) -> tuple[list[Product], int]: ...
    async def update(self, product_id: int, **fields: object) -> Product: ...
    async def delete(self, product_id: int) -> None: ...
    async def take_stock(self, line: StockLine) -> bool:
        """Atomically decrement stock iff enough is available."""
        ...

    async def return_stock(self, line: StockLine) -> None: ...


class ReservationRepository(Protocol):
    async def get(self, reservation_id: str) -> Reservation | None: ...
    async def save(self, reservation: Reservation) -> None: ...
